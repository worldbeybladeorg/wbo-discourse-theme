#!/usr/bin/env node
// Sync the WBO design system from the WordPress theme into this Discourse theme.
//
// WordPress (wp-content/themes/wbo) is the source of truth. Its style.css
// `:root` block is the dark palette and its `[data-theme="light"]` block
// overrides the tokens whose role changes in light mode. This script writes:
//
//   1. common/color_definitions.scss — the region between the BEGIN/END markers
//      becomes a per-scheme `:root` block of `--wbo-*` tokens. Discourse compiles
//      color_definitions.scss once per colour scheme, so `is-light-color-scheme()`
//      picks the light or dark set, and Discourse's own light/dark switching
//      (prefers-color-scheme, or a forced mode) swaps them with no extra CSS.
//   2. about.json — the "WBO" (dark) and "WBO Light" colour schemes, so
//      Discourse's core palette (--primary, --secondary, …, and every shade it
//      derives from them) matches the same tokens.
//   3. scss/wbo-user-menu.scss — assets/user-menu.css (the account panel),
//      with tokens renamed and the panel's root selector mapped to ours.
//   4. javascripts/discourse/lib/wbo-icons.js — the Phosphor icon map from
//      inc/icons.php, so both sides draw the same glyphs.
//
// Every WordPress token `--x` becomes `--wbo-x` here, because several WP names
// (--danger, --success, --text…) collide with Discourse core variables.
//
// Usage:
//   node tools/sync-wp-tokens.mjs <wp theme dir>          # write
//   node tools/sync-wp-tokens.mjs <wp theme dir> --check  # CI: exit 1 on drift
//
// The directory can also come from WBO_WP_THEME. No dependencies.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const wpDir = args.find((a) => !a.startsWith("--")) || process.env.WBO_WP_THEME;
if (!wpDir || !existsSync(join(wpDir, "style.css"))) {
  console.error("usage: sync-wp-tokens.mjs <wp-content/themes/wbo> [--check]");
  process.exit(2);
}
const src = join(wpDir, "style.css");

const BEGIN = "// ── BEGIN wbo-tokens (generated by tools/sync-wp-tokens.mjs — do not edit) ──";
const END = "// ── END wbo-tokens ──";

// ── Parse ───────────────────────────────────────────────────────────────────

const css = readFileSync(src, "utf8")
  .replace(/\r\n/g, "\n")
  .replace(/\/\*[\s\S]*?\*\//g, "");

// First top-level block whose selector is exactly `selector`.
function block(selector) {
  let depth = 0;
  let start = 0;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === "{") {
      if (depth === 0) {
        const sel = css.slice(start, i).trim();
        if (sel === selector) {
          const end = css.indexOf("}", i);
          return css.slice(i + 1, end);
        }
      }
      depth++;
    } else if (c === "}") {
      depth--;
      if (depth === 0) {
        start = i + 1;
      }
    } else if (c === ";" && depth === 0) {
      start = i + 1;
    }
  }
  throw new Error(`no top-level "${selector}" block in ${src}`);
}

function decls(body) {
  const out = new Map();
  for (const raw of body.split(";")) {
    const d = raw.trim();
    const m = d.match(/^(--[\w-]+|color-scheme)\s*:\s*([\s\S]+)$/);
    if (m) {
      out.set(m[1], m[2].replace(/\s+/g, " ").trim());
    }
  }
  return out;
}

const dark = decls(block(":root"));
const lightOnly = decls(block('[data-theme="light"]'));
const light = new Map([...dark, ...lightOnly]);

// ── Emit SCSS ───────────────────────────────────────────────────────────────

const rename = (v) => v.replace(/var\(--([\w-]+)/g, "var(--wbo-$1");
const prop = (k) => (k === "color-scheme" ? k : `--wbo-${k.slice(2)}`);

function scssBlock(map, indent) {
  const pad = " ".repeat(indent);
  return [...map]
    .map(([k, v]) => `${pad}${prop(k)}: ${rename(v)};`)
    .join("\n");
}

const scss = [
  BEGIN,
  `// Source: WordPress themes/wbo/style.css (:root + [data-theme="light"]).`,
  `// Regenerate with: node tools/sync-wp-tokens.mjs <wp-content/themes/wbo>`,
  "@if is-light-color-scheme() {",
  "  :root {",
  scssBlock(light, 4),
  "  }",
  "} @else {",
  "  :root {",
  scssBlock(dark, 4),
  "  }",
  "}",
  END,
].join("\n");

// ── Resolve to hex for the Discourse palette ────────────────────────────────

function hexToRgb(h) {
  h = h.replace("#", "");
  if (h.length === 3) {
    h = [...h].map((c) => c + c).join("");
  }
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
}
const toHex = (rgb) =>
  rgb.map((n) => Math.round(n).toString(16).padStart(2, "0")).join("");

// Resolve a token to an opaque sRGB triple. Translucent values are composited
// over `base` (the card surface), which is where Discourse paints them.
function resolve(map, name, base) {
  let v = map.get(name);
  if (v === undefined) {
    throw new Error(`token ${name} not found`);
  }
  for (let i = 0; i < 10 && /var\(--/.test(v); i++) {
    v = v.replace(/var\((--[\w-]+)\)/g, (_, n) => map.get(n) ?? "");
  }
  let m;
  if ((m = v.match(/^#([0-9a-f]{3}|[0-9a-f]{6})$/i))) {
    return hexToRgb(m[1]);
  }
  if ((m = v.match(/^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/))) {
    const rgb = [m[1], m[2], m[3]].map(Number);
    const a = m[4] === undefined ? 1 : Number(m[4]);
    const b = base || [255, 255, 255];
    return rgb.map((c, i) => c * a + b[i] * (1 - a));
  }
  throw new Error(`cannot resolve ${name} = ${v} to a colour`);
}

// Discourse palette slot ← WBO token. Discourse derives every --primary-low,
// --tertiary-medium … shade from these, so a slot only needs its base colour.
const PALETTE = {
  primary: "--text",
  secondary: "--surface",
  tertiary: "--blue-text",
  quaternary: "--orange-text",
  header_background: "--chrome-bg",
  header_primary: "--text",
  highlight: "--orange",
  selected: "--bell-tab-active",
  hover: "--bell-hover",
  danger: "--danger-text",
  success: "--success-text",
  love: "--organize",
};

function palette(map) {
  const surface = resolve(map, "--surface");
  const out = {};
  for (const [slot, token] of Object.entries(PALETTE)) {
    out[slot] = toHex(resolve(map, token, surface));
  }
  return out;
}

// ── Write ───────────────────────────────────────────────────────────────────

const cdPath = join(ROOT, "common/color_definitions.scss");
const cd = readFileSync(cdPath, "utf8");
const b = cd.indexOf(BEGIN);
const e = cd.indexOf(END);
const nextCd =
  b === -1
    ? `${cd.trimEnd()}\n\n${scss}\n`
    : cd.slice(0, b) + scss + cd.slice(e + END.length);

const aboutPath = join(ROOT, "about.json");
const about = JSON.parse(readFileSync(aboutPath, "utf8"));
about.color_schemes = {
  // "WBO" keeps its name so Discourse updates the existing dark scheme in
  // place rather than creating a new one.
  WBO: palette(dark),
  "WBO Light": palette(light),
};
const nextAbout = JSON.stringify(about, null, 2) + "\n";

// ── The account panel stylesheet ────────────────────────────────────────────
//
// Copied rule for rule. Only two things change: tokens get the --wbo- prefix,
// and WordPress's panel/trigger class names map to ours (Discourse already
// owns .user-menu*). Anything else the panel needs lives in wbo-site-nav.scss.

const SELECTORS = [
  [".user-menu-dropdown.um-card", ".wbo-um-panel.um-card"],
  [".user-menu-trigger", ".wbo-user-menu-trigger"],
  [".user-menu-panel-icon", ".wbo-user-menu-panel-icon"],
];
let umCss = readFileSync(join(wpDir, "assets/user-menu.css"), "utf8").replace(
  /\r\n/g,
  "\n"
);
for (const [from, to] of SELECTORS) {
  umCss = umCss.split(from).join(to);
}
umCss = umCss.replace(/var\(--([\w-]+)/g, "var(--wbo-$1");
const nextUm =
  "// GENERATED by tools/sync-wp-tokens.mjs from WordPress\n" +
  "// themes/wbo/assets/user-menu.css — do not edit here; edit WordPress and\n" +
  "// re-run the sync. Discourse-only additions go in wbo-site-nav.scss.\n\n" +
  umCss.trimEnd() +
  "\n";
const umPath = join(ROOT, "scss/wbo-user-menu.scss");

// ── Icons ───────────────────────────────────────────────────────────────────

const iconsPhp = readFileSync(join(wpDir, "inc/icons.php"), "utf8");
const icons = {};
for (const m of iconsPhp.matchAll(/^\s*'([\w-]+)'\s*=>\s*'(<[^']+)',?\s*$/gm)) {
  icons[m[1]] = m[2];
}
if (Object.keys(icons).length < 10) {
  throw new Error("could not read the icon map from inc/icons.php");
}
const nextIcons =
  "// GENERATED by tools/sync-wp-tokens.mjs from WordPress themes/wbo/inc/icons.php\n" +
  "// (Phosphor Regular, 256 viewBox, fill-based). Do not edit here.\n\n" +
  "export const ICON_PATHS = " +
  JSON.stringify(icons, null, 2) +
  ";\n";
const iconsPath = join(ROOT, "javascripts/discourse/lib/wbo-icons.js");

const outputs = [
  ["common/color_definitions.scss", cdPath, nextCd],
  ["about.json", aboutPath, nextAbout],
  ["scss/wbo-user-menu.scss", umPath, nextUm],
  ["javascripts/discourse/lib/wbo-icons.js", iconsPath, nextIcons],
];
const drift = outputs
  .filter(([, path, next]) => !existsSync(path) || readFileSync(path, "utf8") !== next)
  .map(([name]) => name);

if (check) {
  if (drift.length) {
    console.error(`Out of sync with WordPress tokens: ${drift.join(", ")}`);
    console.error("Run: node tools/sync-wp-tokens.mjs <wp-content/themes/wbo>");
    process.exit(1);
  }
  console.log("Discourse tokens match WordPress.");
} else {
  for (const [, path, next] of outputs) {
    writeFileSync(path, next);
  }
  console.log(
    drift.length ? `Updated: ${drift.join(", ")}` : "Already in sync."
  );
}
